const esc = (v) => String(v ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

// variant: '' | 'danger' | 'success' | 'primary'
export function iconBtn({ icon: name, title, cls = '', variant = '', attrs = '' }) {
  return `<button type="button" class="icon-btn${variant ? ' icon-btn--' + variant : ''} ${cls}" title="${esc(title)}" aria-label="${esc(title)}" ${attrs}>${icon(name)}</button>`;
}
